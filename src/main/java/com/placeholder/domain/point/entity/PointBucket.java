package com.placeholder.domain.point.entity;

/**
 * 포인트 재원 계층 (ADR-020).
 *
 * <p>같은 1,000P라도 어디서 왔느냐에 따라 할 수 있는 일이 다르다 — 쿠폰으로 받은 포인트는
 * 환불 재원이 될 수 없고, 현금으로 산 포인트는 될 수 있다. 이 구분이 없으면
 * "현금 충전 → 좌석에 소진 → 쿠폰 상환 → 결제 취소" 순서로 <b>쿠폰이 현금으로 환전된다</b>.
 *
 * <p><b>⚠️ 선언 순서가 곧 소모 우선순위다.</b> 순서를 바꾸면 소모 정책이 바뀐다.
 * "사라질 것부터, 돌려줄 수 있는 것은 마지막에" — 반대로 가면 각각 이렇게 손해가 난다:
 *
 * <ul>
 *   <li>{@code EVENT}를 나중에 쓰면 → <b>사용자</b>가 손해 (쓸 수 있던 포인트가 만료로 소멸)</li>
 *   <li>{@code PAID}를 먼저 쓰면 → <b>서비스</b>가 손해 (환불 가능 잔액이 먼저 사라진다)</li>
 * </ul>
 */
public enum PointBucket {

    /**
     * 기간제 포인트 — 판촉 쿠폰으로 지급되고 기한이 지나면 소멸한다. 환불 불가.
     *
     * <p><b>예약 대상인 {@code Event} 엔티티와는 무관하다.</b> 이름이 겹칠 뿐 다른 축이다.
     *
     * <p>소멸은 아직 구현되지 않았다 — {@code Coupon}에 유효기간 필드가 없어 발급 수단 자체가
     * 없으므로 현재 이 버킷의 잔액은 항상 0이다. 계층을 미리 열어두는 이유는 확장 비용 때문이다
     * (ADR-020 6번).
     */
    EVENT,

    /** 무기한 쿠폰 상환분. 환불 불가, 만료 없음. */
    FREE,

    /** 현금 결제로 충전된 포인트 (ADR-018). <b>유일한 환불 재원.</b> */
    PAID
}
